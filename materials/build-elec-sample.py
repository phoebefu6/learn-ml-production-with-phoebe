"""Build the Elec2 bench sample shipped as assets/elec-sample.js.

Source: OpenML dataset 151 "electricity" (ELEC2, Harries 1999; normalised by A. Bifet),
downloaded without login from https://openml.org/data/v1/download/2419/electricity.arff

What the sample keeps and how it was compacted (declared on the bench page):
  * every 3rd half-hour row, in time order (rows 0, 3, 6, ...): 15,104 of 45,312 rows,
    one row every 1.5 hours, 16 rows a day, 112 a week. The order is untouched, so the drift is too.
  * five numeric inputs (nswprice, nswdemand, vicprice, vicdemand, transfer), each already
    scaled 0..1 by OpenML, quantised to an integer 0..255 (round(v * 255)).
  * the class label, UP = 1, DOWN = 0.
  * period (half-hour of day) and day of week are NOT stored: the file is a gapless 944 x 48
    grid, so both follow from the row index (checked below). Sin/cos of the period are shipped as
    a 16-entry integer table so browser and Python never call a trig function.

Usage: python3 materials/build-elec-sample.py   (writes assets/elec-sample.js and
materials/elec-sample.json)
"""
import json, math, os, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
URL = "https://openml.org/data/v1/download/2419/electricity.arff"
STEP = 3


def load(path_or_url=URL):
    cache = os.environ.get("ELEC_ARFF")
    if cache and os.path.exists(cache):
        text = open(cache).read()
    else:
        text = urllib.request.urlopen(path_or_url).read().decode()
    rows = []
    for line in text.splitlines():
        line = line.strip()
        if not line or line[0] in "@%":
            continue
        rows.append(line.split(","))
    return rows


def main():
    rows = load()
    assert len(rows) == 45312, len(rows)
    for i, r in enumerate(rows):  # period and day follow from the index
        assert round(float(r[2]) * 47) == i % 48
        assert int(r[1]) == (i // 48 + 1) % 7 + 1
    keep = rows[::STEP]
    cols = {k: [] for k in ("nswprice", "nswdemand", "vicprice", "vicdemand", "transfer")}
    idx = {"nswprice": 3, "nswdemand": 4, "vicprice": 5, "vicdemand": 6, "transfer": 7}
    labels = []
    for r in keep:
        for k, j in idx.items():
            v = round(float(r[j]) * 255)
            assert 0 <= v <= 255
            cols[k].append(v)
        labels.append(1 if r[8] == "UP" else 0)
    periods = sorted({(i * STEP) % 48 for i in range(len(keep))})
    sin_t = [round(127 * math.sin(2 * math.pi * p / 48)) for p in periods]
    cos_t = [round(127 * math.cos(2 * math.pi * p / 48)) for p in periods]
    data = {
        "source": "OpenML 151 electricity (ELEC2, Harries 1999), every 3rd half-hour, inputs quantised 0-255",
        "n": len(keep),
        "step": STEP,
        "first_day_of_week": int(rows[0][1]),
        "hex": {k: "".join("%02x" % v for v in vs) for k, vs in cols.items()},
        "labels": "".join(str(b) for b in labels),
        "period_sin": sin_t,
        "period_cos": cos_t,
    }
    blob = json.dumps(data, separators=(",", ":"))
    with open(os.path.join(HERE, "elec-sample.json"), "w") as f:
        f.write(blob)
    with open(os.path.join(REPO, "assets", "elec-sample.js"), "w") as f:
        f.write("/* Elec2 bench sample, generated by materials/build-elec-sample.py with json.dumps. "
                "OpenML 151 electricity (Harries 1999). Every 3rd half-hour row, inputs quantised 0-255. */\n")
        f.write("window.ELEC_SAMPLE = " + blob + ";\n")
    print("rows", len(keep), "UP share", round(sum(labels) / len(labels), 4), "bytes", len(blob))


if __name__ == "__main__":
    main()
